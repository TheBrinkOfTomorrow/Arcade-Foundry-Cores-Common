#!/usr/bin/env python3
"""Writes the file list a folder-based core (Lindbergh, Chihiro) checks a
game against (afcore check_roms, include/afcommon/filecheck.h): every
regular file's path, size and CRC-32, from a known-good copy of the game.

    make_filelist.py hotd4a.tar -o filelists/hotd4a.h
    make_filelist.py ~/Games/ArcadeFoundry/Lindbergh/hotd4a -o filelists/hotd4a.h

The input is the game's .tar (as the app downloads it) or its folder.
Paths are relative to the game folder: the folder that holds `--marker`
(default disk0) when there is one, else the tar's one top folder if every
file is under it. Only names, sizes and CRCs are written, nothing of the
files themselves.
"""
import argparse
import os
import sys
import tarfile
import zlib

CHUNK = 1 << 20


def crc_of(f):
    crc = 0
    while True:
        b = f.read(CHUNK)
        if not b:
            return crc & 0xFFFFFFFF
        crc = zlib.crc32(b, crc)


def from_tar(path):
    out = []
    with tarfile.open(path, 'r:*') as t:
        for m in t:
            if m.isfile():
                with t.extractfile(m) as f:
                    out.append((m.name, m.size, crc_of(f)))
    return out


def from_folder(path):
    out = []
    for dirpath, dirs, files in os.walk(path):
        dirs.sort()
        for name in sorted(files):
            full = os.path.join(dirpath, name)
            if os.path.islink(full) or not os.path.isfile(full):
                continue
            with open(full, 'rb') as f:
                out.append((os.path.relpath(full, path).replace(os.sep, '/'), os.path.getsize(full), crc_of(f)))
    return out


def rebase(entries, marker):
    """Paths relative to the game folder."""
    parts = [(e[0][2:] if e[0].startswith('./') else e[0]).split('/') for e in entries]
    cut = None
    if marker:
        for p in parts:
            if marker in p[:-1]:
                cut = p.index(marker)
                break
    if cut is None:
        tops = {p[0] for p in parts}
        cut = 1 if len(tops) == 1 and all(len(p) > 1 for p in parts) else 0
    out = []
    for (name, size, crc), p in zip(entries, parts):
        rel = '/'.join(p[cut:])
        if not rel or '..' in p:
            sys.exit(f'{name}: outside the game folder')
        out.append((rel, size, crc))
    return sorted(out)


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def header(entries, source):
    lines = [f'/* Generated by tools/filelist/make_filelist.py from {os.path.basename(source.rstrip("/"))}: do not edit. */',
             '#include "afcommon/filecheck.h"', '',
             f'#define AFC_FILELIST_COUNT {len(entries)}',
             'static const afc_listed_file afc_filelist[] = {']
    lines += [f'    {{{c_string(p)}, {s}u, 0x{c:08x}u}},' for p, s, c in entries]
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('source', help='the game\'s .tar or its folder')
    ap.add_argument('-o', '--out', required=True, help='the header to write')
    ap.add_argument('--marker', default='disk0', help='the folder the game folder holds (empty: none)')
    a = ap.parse_args()
    entries = from_folder(a.source) if os.path.isdir(a.source) else from_tar(a.source)
    if not entries:
        sys.exit(f'{a.source}: no files')
    entries = rebase(entries, a.marker)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write(header(entries, a.source))
    print(f'{a.out}: {len(entries)} files, {sum(e[1] for e in entries) / 1e9:.2f} GB')


if __name__ == '__main__':
    main()
